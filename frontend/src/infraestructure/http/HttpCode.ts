/**
 * The enum HttpCode contains some HTTP protocol codes.
 */
enum HttpCode {

    /**
     * Success code.
     */
    SUCCESS = 200,

    /**
     * Bad request code.
     */
    BAD_REQUEST = 400,

    /**
     * Forbidden code.
     */
    FORBIDDEN = 401,

    /**
     * Not found resource code.
     */
    NOT_FOUND = 404
};

// Exports the enum HttpCode.
export default HttpCode;