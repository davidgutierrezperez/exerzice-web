/**
 * The enum HttpMethod contains the HTTP methods available.
 */
enum HttpMethod {

    /**
     * GET method.
     */
    GET = 'GET',

    /**
     * POST method.
     */
    POST = 'POST',

    /**
     * PUT method.
     */
    PUT = 'PUT',

    /**
     * DELETE method.
     */
    DELETE = 'DELETE'
};

// Exports the enum HttpMethod.
export default HttpMethod;